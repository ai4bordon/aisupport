/**
 * Режим эскалации (ADR-0014).
 *
 * Три режима различаются тем, что происходит с вопросом, на который в базе
 * знаний нет подтверждённого ответа:
 *
 * - `off` — агент отвечает честно: говорит, что в опубликованной базе ответа
 *   нет, задаёт один уточняющий вопрос и предлагает передать вопрос
 *   менеджеру. Очередь менеджера не создаётся, неподтверждённые факты не
 *   выдумываются. Режим для локальной отладки: так видно, как агент ведёт
 *   себя на вопросе без источника, и не создаётся поток эскалаций.
 * - `notice` — эскалация создаётся, а клиент получает нейтральное
 *   уведомление без сроков и обязательств. Режим стенда.
 * - `on` — поведение по R4: эскалация создаётся, клиент получает статус
 *   передачи в интерфейсе, неподтверждённого обещания не получает.
 *
 * Режим не отменяет правило «суммы и условия только из источника»: в режиме
 * `off` агент не отвечает по памяти модели, а сообщает об отсутствии
 * подтверждённого ответа.
 */

export type EscalationMode = "off" | "notice" | "on";

/** Режим по умолчанию: локальная отладка без создания очереди менеджера. */
export const DEFAULT_ESCALATION_MODE: EscalationMode = "off";

/**
 * Текущий режим эскалации из переменной окружения.
 *
 * Неизвестное значение трактуется как `off`: режим `on` создаёт очередь
 * менеджера, и включать его опечаткой в конфиге нельзя.
 */
export function escalationMode(): EscalationMode {
  const raw = (process.env.ESCALATION_MODE ?? "").trim().toLowerCase();
  if (raw === "notice" || raw === "on") {
    return raw;
  }
  return DEFAULT_ESCALATION_MODE;
}

/**
 * Нужно ли создавать запись в очереди менеджера.
 *
 * В режиме `off` очередь не создаётся: вопрос уточняется у клиента, а не
 * перекладывается менеджеру.
 */
export function createsManagerQueue(mode: EscalationMode = escalationMode()): boolean {
  return mode !== "off";
}

/**
 * Нужно ли отправлять клиенту нейтральное уведомление об эскалации.
 *
 * Только в режиме `notice`: в режиме `on` клиент видит статус передачи в
 * интерфейсе, а в режиме `off` вопрос уточняется напрямую.
 */
export function notifiesClient(mode: EscalationMode = escalationMode()): boolean {
  return mode === "notice";
}

/**
 * Ответ при отсутствии подтверждённого источника в режиме `off`.
 *
 * Честный ответ без выдуманных фактов: агент говорит, что точного ответа у
 * него пока нет, и задаёт один уточняющий вопрос. Предложения передать
 * вопрос менеджеру здесь нет — очередь в этом режиме не создаётся, и
 * обещать передачу, которая не была создана, нельзя (ADR-0014).
 *
 * Внутренние термины в тексте клиенту не попадают: где именно агент искал
 * ответ, клиенту знать не нужно (решение владельца от 27.11.2026).
 */
export function noSourceAnswer(): string {
  return (
    "У меня пока нет точного ответа на этот вопрос. " +
    "Уточните, пожалуйста, какой продукт и версия вас интересуют — я проверю данные."
  );
}
