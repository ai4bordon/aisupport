/**
 * Нормализация приветствия в ответе агента.
 *
 * Аудит 28.11, пункт P2-10: ответ на вопрос «Здравствуйте, как получить
 * лицензию?» начинался с «Здравствуйте!», и приветствие дублировалось —
 * в вопросе и в ответе. Выглядело так, будто агент не прочитал вопрос.
 *
 * Правило простое: если вопрос клиента уже начат с приветствия, а ответ
 * начинается с него же, приветствие из ответа убирается. Если вопрос был
 * без приветствия, ответ приветствие сохраняет — начать разговор с
 * приветствия правильно.
 */

/**
 * Приветствия в начале сообщения.
 *
 * Граница слова задана через lookahead, а не через `\b`: в JavaScript `\b`
 * опирается на ASCII-класс `\w`, поэтому на кириллице он не срабатывает и
 * шаблон «здра» не находил «Здравствуйте».
 */
const GREETING_PREFIX =
  /^\s*(здра(?:вствуйте|ствуй)|добрый\s+(?:день|вечер)|доброе\s+утро|привет|приветствую|hello|hi|hey)(?![а-яёa-z])[\s,.!—-]*/iu;

/** Есть ли приветствие в начале сообщения. */
export function startsWithGreeting(text: string): boolean {
  return GREETING_PREFIX.test(text);
}

/**
 * Убирает приветствие из ответа, если оно уже было в вопросе.
 *
 * Возвращает ответ без ведущего приветствия и следующей за ним пустой
 * строки. Текст ответа в остальном не меняется.
 */
export function dropDuplicateGreeting(question: string, answer: string): string {
  if (!startsWithGreeting(question)) {
    return answer;
  }
  const stripped = answer.replace(GREETING_PREFIX, "");
  // После приветствия остаётся пустая строка или пробелы — их убираем,
  // иначе ответ начинается с пустого абзаца.
  return stripped.replace(/^\s+/u, "");
}
