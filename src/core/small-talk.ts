/**
 * Приветствие и общие вопросы о возможностях агента.
 *
 * Ответ на такие сообщения не требует подтверждённого источника: это не
 * вопрос о продукте, а начало диалога. Без отдельной ветки «Привет»
 * уходил в поиск по базе знаний, не находил совпадений и превращался в
 * эскалацию — клиент получал тишину вместо ответа.
 *
 * Ветка срабатывает до поиска по БЗ и не требует вызова модели: ответ
 * задаётся текстом, а не генерируется, поэтому не может содержать
 * неподтверждённых фактов.
 */

/**
 * Приветствие и короткие реплики без вопроса о продукте.
 *
 * Границы слова заданы явно, а не через `\b`: в JavaScript `\b` опирается
 * на ASCII-класс `\w`, поэтому на кириллице он не срабатывает и шаблон
 * «привет» не находил «Привет».
 */
const GREETING_PATTERNS: RegExp[] = [
  /^\s*(привет|здравствуй(те)?|добрый\s+(день|вечер)|приветствую|hello|hi|hey)(?![а-яёa-z])[\s!.?,]*$/iu,
  /^\s*(доброе\s+утро)(?![а-яёa-z])[\s!.?,]*$/iu,
];

/** Вопросы о том, что агент умеет. */
const CAPABILITY_PATTERNS: RegExp[] = [
  /^\s*(что\s+(вы|ты)\s+(умеете|умеешь|можете|можешь)|что\s+(умеете|умеешь)|чем\s+(вы|ты)\s+(можете|можешь)\s+помочь|как\s+(вы|ты)\s+работаешь)(?![а-яёa-z])[\s!.?,]*$/iu,
  /^\s*(ты\s+кто|кто\s+ты|представься|расскажи\s+о\s+себе)(?![а-яёa-z])[\s!.?,]*$/iu,
];

/** Ответ на приветствие. */
const GREETING_ANSWER =
  "Здравствуйте! Я агент службы поддержки ПАО «Софтлайн». " +
  "Спросите про лицензии, тарифы, заказы и документы — отвечу по базе знаний.";

/** Ответ на вопрос о возможностях. */
const CAPABILITY_ANSWER =
  "Я отвечаю по базе знаний: лицензии и тарифы, заказы и поставки, кабинет и авторизация, " +
  "документы и счета. Кроме того, я могу подобрать товар, рассчитать стоимость, " +
  "сформировать коммерческое предложение и счёт. Если ответа в базе нет, вопрос передаётся менеджеру.";

/**
 * Ответ на приветствие или общий вопрос о возможностях.
 *
 * Возвращает `null`, если сообщение не относится к началу диалога: дальше
 * работает обычный путь «классификация → поиск по БЗ».
 */
export function smallTalkAnswer(text: string): string | null {
  const trimmed = text.trim();
  if (trimmed.length === 0) {
    return null;
  }
  if (GREETING_PATTERNS.some((pattern) => pattern.test(trimmed))) {
    return GREETING_ANSWER;
  }
  if (CAPABILITY_PATTERNS.some((pattern) => pattern.test(trimmed))) {
    return CAPABILITY_ANSWER;
  }
  return null;
}
