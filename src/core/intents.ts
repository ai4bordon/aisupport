/**
 * Промпт классификатора с контекстом диалога.
 *
 * `context` — состояние диалога: если подбор уже начат, ответ на
 * уточняющий вопрос («бюджета нет, инфраструктура своя») продолжает тот же
 * класс, а не трактуется как `out_of_scope`. Без контекста второй ход
 * диалога уходил в базу знаний вместо каталога.
 */
export function classifierPrompt(context: string | null): string {
  const lines = [CLASSIFIER_PROMPT];
  if (context !== null && context.length > 0) {
    lines.push(
      "",
      `Контекст диалога: ${context}. Ответь тем же классом, что и начатый подбор.`,
    );
  }
  return lines.join("\n");
}

/**
 * Контекст диалога для классификатора.
 *
 * Собирается из собранных слотов: если подбор уже идёт, ответ на
 * уточняющий вопрос продолжает тот же класс. Без этого классификатор
 * трактовал «бюджета нет, инфраструктура своя» как `out_of_scope`, и запрос
 * уходил в базу знаний вместо каталога.
 */
export function classifierContext(slots: {
  discovery: string | null;
  productQuery: string | null;
  quantity: number | null;
} | null): string | null {
  if (slots === null) return null;
  if (slots.discovery === null && slots.productQuery === null) return null;
  if (slots.discovery !== null) {
    return `идёт подбор продукта по задаче, собрано: количество ${slots.quantity ?? "не выяснено"}`;
  }
  return `идёт подбор продукта ${slots.productQuery}`;
}

