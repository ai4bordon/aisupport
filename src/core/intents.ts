/**
 * Таксономия намерений обращений и маршрутизация.
 *
 * Классификатор отвечает строго кодом класса из закрытого списка. Свободный
 * текст не допускается: по нему нельзя надёжно выбрать маршрут, и ответ
 * «Ответ из памяти модели» в трассе не говорил ничего о том, куда ушёл
 * запрос.
 *
 * Маршруты классов не смешиваются:
 *
 * - `greeting`, `self_info` → профиль агента: кто я, что умею, чего не
 *   делаю. Без поиска по базе знаний и без модели для фактов;
 * - `company_info`, `howto`, `complaint` → поиск по базе знаний, ответ по
 *   переданным чанкам;
 * - `product_known`, `product_unknown`, `quote`, `terms` → каталог: слоты,
 *   расчёт кодом, проверка полномочий. В каталог по «доставке» не ходим, в
 *   статьи по «цене MDaemon» не ходим.
 */

/** Классы намерений. */
export const INTENT_CLASSES = [
  "greeting",
  "self_info",
  "company_info",
  "howto",
  "complaint",
  "product_known",
  "product_unknown",
  "quote",
  "terms",
  "out_of_scope",
] as const;

export type IntentClass = (typeof INTENT_CLASSES)[number];

/** Маршрут обработки намерения. */
export type IntentRoute = "profile" | "knowledge" | "catalog";

/**
 * Маршрут каждого класса.
 *
 * `greeting` и `self_info` — профиль агента; `company_info`, `howto`,
 * `complaint` — база знаний; остальные — каталог.
 */
export const ROUTE_BY_CLASS: Record<IntentClass, IntentRoute> = {
  greeting: "profile",
  self_info: "profile",
  company_info: "knowledge",
  howto: "knowledge",
  complaint: "knowledge",
  product_known: "catalog",
  product_unknown: "catalog",
  quote: "catalog",
  terms: "catalog",
  out_of_scope: "knowledge",
};

/** Признак класса в ответе классификатора. */
export function isIntentClass(value: string): value is IntentClass {
  return (INTENT_CLASSES as readonly string[]).includes(value);
}

/**
 * Нормализация ответа классификатора.
 *
 * Модель может вернуть код в кавычках, с точкой или с пояснением после
 * запятой. Берётся первый код из закрытого списка; неизвестное значение —
 * `out_of_scope`, потому что сомневаться надо в сторону осторожной ветки.
 */
export function normalizeIntent(raw: string): IntentClass {
  const trimmed = raw.trim().toLowerCase();
  const direct = trimmed.match(/[a-z_]+/u);
  if (direct?.[0] !== undefined && isIntentClass(direct[0])) {
    return direct[0];
  }
  for (const candidate of INTENT_CLASSES) {
    if (trimmed.includes(candidate)) {
      return candidate;
    }
  }
  return "out_of_scope";
}

