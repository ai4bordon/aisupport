import { afterAll } from "vitest";

/**
 * Общее окружение тестового файла.
 *
 * Тесты меняют переменные окружения (арендатор, режим эскалации, каталог
 * документов). Такие значения живут на уровне процесса, поэтому без
 * восстановления соседний файл наследовал чужое состояние, и результат
 * прогона зависел от порядка файлов (аудит B14).
 *
 * Здесь значения не мутируются «втихую»: помощник запоминает исходное
 * значение переменной и возвращает его, когда файл закончил работу.
 *
 * Хук регистрируется на уровне модуля, поэтому относится к тому файлу,
 * который импортировал помощник. При `isolate: false` (общий воркер на
 * несколько файлов) модуль кэшируется, и восстановление достаётся первому
 * импортировавшему файлу; остальные файлы чистят окружение сами. Штатная
 * конфигурация использует изоляцию по умолчанию, поэтому там восстановление
 * выполняется для каждого файла.
 */
const pristineValues = new Map<string, string | undefined>();

/**
 * Присваивает переменную окружения на время работы тестового файла.
 *
 * Исходное значение запоминается при первом обращении и возвращается
 * автоматически; повторные вызовы в том же файле просто переприсваивают
 * значение.
 */
export function scopeEnv(name: string, value: string): void {
  if (!pristineValues.has(name)) {
    pristineValues.set(name, process.env[name]);
  }
  process.env[name] = value;
}

afterAll(() => {
  for (const [name, value] of pristineValues) {
    if (value === undefined) delete process.env[name];
    else process.env[name] = value;
  }
  pristineValues.clear();
});
