import { describe, expect, it } from "vitest";

import { dropDuplicateGreeting, startsWithGreeting } from "@/core/greeting";

/**
 * Приветствие в ответе агента (UX-аудит 28.11, пункт P2-10).
 *
 * Ответ на вопрос «Здравствуйте, как получить лицензию?» начинался с
 * «Здравствуйте!»: приветствие дублировалось — в вопросе и в ответе.
 */

describe("приветствие в ответе агента", () => {
  it("узнаёт приветствие в начале сообщения", () => {
    expect(startsWithGreeting("Здравствуйте!")).toBe(true);
    expect(startsWithGreeting("Добрый день")).toBe(true);
    expect(startsWithGreeting("Привет")).toBe(true);
    expect(startsWithGreeting("Как получить лицензию?")).toBe(false);
  });

  it("убирает приветствие из ответа, если клиент уже поздоровался", () => {
    const answer = dropDuplicateGreeting(
      "Здравствуйте! Как получить лицензию?",
      "Здравствуйте! Лицензия выдаётся в личном кабинете.",
    );

    expect(answer).toBe("Лицензия выдаётся в личном кабинете.");
  });

  it("оставляет приветствие, если клиент не здоровался", () => {
    const answer = dropDuplicateGreeting(
      "Как получить лицензию?",
      "Здравствуйте! Лицензия выдаётся в личном кабинете.",
    );

    expect(answer).toBe("Здравствуйте! Лицензия выдаётся в личном кабинете.");
  });

  it("не трогает ответ, где приветствия нет", () => {
    const answer = dropDuplicateGreeting(
      "Здравствуйте! Как получить лицензию?",
      "Лицензия выдаётся в личном кабинете.",
    );

    expect(answer).toBe("Лицензия выдаётся в личном кабинете.");
  });

  it("убирает пустую строку, оставшуюся после приветствия", () => {
    const answer = dropDuplicateGreeting(
      "Добрый день, как получить лицензию?",
      "Добрый день!\n\nЛицензия выдаётся в личном кабинете.",
    );

    expect(answer).toBe("Лицензия выдаётся в личном кабинете.");
  });
});
